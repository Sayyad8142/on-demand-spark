#!/usr/bin/env bash
# Generates every Didi Now Partner icon from ONE master file:
#   branding/app-icon-master.png   (square PNG, >= 1024px, pink background, white text)
# Run:  bun run icons:generate     (needs ImageMagick: `magick` or `convert`)
# Outputs are committed, so builds without ImageMagick still use the current icons.
set -euo pipefail
cd "$(dirname "$0")/.."

MASTER="branding/app-icon-master.png"
BG="#F90272"   # icon background pink (sampled from the master)
[ -f "$MASTER" ] || { echo "Missing $MASTER"; exit 1; }

if command -v magick >/dev/null 2>&1; then IM=(magick)
elif command -v convert >/dev/null 2>&1; then IM=(convert)
else echo "ImageMagick not found - skipping icon generation (committed icons are used)."; exit 0; fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
RES="android/app/src/main/res"

# 1. Full-bleed square (fill the master's white rounded corners with pink).
"${IM[@]}" "$MASTER" -resize 1024x1024! -fuzz 20% -fill "$BG" \
  -draw "color 0,0 floodfill" -draw "color 1023,0 floodfill" \
  -draw "color 0,1023 floodfill" -draw "color 1023,1023 floodfill" "$TMP/full.png"

# 2. White text only, on transparency (alpha from brightness).
"${IM[@]}" "$TMP/full.png" -colorspace gray -level 55%,95% "$TMP/mask.png"
"${IM[@]}" -size 1024x1024 xc:white "$TMP/mask.png" -alpha off -compose CopyOpacity -composite -trim +repage "$TMP/text.png"

# Text centred on a canvas; $1 = canvas size, $2 = text width as % of canvas, $3 = bg, $4 = out
place_text() {
  local w=$(( $1 * $2 / 100 ))
  "${IM[@]}" -size "${1}x${1}" "xc:$3" \( "$TMP/text.png" -resize "${w}x" \) -gravity center -composite "$4"
}

# 3. Android adaptive foreground: 108dp canvas, text kept inside the 66dp safe circle.
place_text 1024 54 none "$TMP/fg.png"
# Legacy square icon (rounded corners) and round icon.
place_text 1024 84 "$BG" "$TMP/square.png"
"${IM[@]}" "$TMP/square.png" -alpha set \( -size 1024x1024 xc:none -fill white -draw "roundrectangle 0,0 1023,1023 180,180" \) \
  -compose DstIn -composite "$TMP/legacy.png"
place_text 1024 72 "$BG" "$TMP/sq_round.png"
"${IM[@]}" "$TMP/sq_round.png" -alpha set \( -size 1024x1024 xc:none -fill white -draw "circle 512,512 512,0" \) \
  -compose DstIn -composite "$TMP/round.png"

for d in "mdpi 48 108" "hdpi 72 162" "xhdpi 96 216" "xxhdpi 144 324" "xxxhdpi 192 432"; do
  set -- $d
  mkdir -p "$RES/mipmap-$1"
  "${IM[@]}" "$TMP/legacy.png" -resize "${2}x${2}" "$RES/mipmap-$1/ic_launcher.png"
  "${IM[@]}" "$TMP/round.png"  -resize "${2}x${2}" PNG32:"$RES/mipmap-$1/ic_launcher_round.png"
  "${IM[@]}" "$TMP/fg.png"     -resize "${3}x${3}" "$RES/mipmap-$1/ic_launcher_foreground.png"
done
mkdir -p "$RES/mipmap-anydpi-v26" "$RES/values"
for n in ic_launcher ic_launcher_round; do
cat > "$RES/mipmap-anydpi-v26/$n.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-app-icons.sh - do not edit -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
XML
done
cat > "$RES/values/ic_launcher_background.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-app-icons.sh - do not edit -->
<resources>
    <color name="ic_launcher_background">$BG</color>
</resources>
XML
# Kept for existing @drawable/app_icon references (in-app native screens).
"${IM[@]}" "$TMP/legacy.png" -resize 512x512 "$RES/drawable/app_icon.png"

# 4. Web / PWA / favicon / in-app logo.
"${IM[@]}" "$TMP/legacy.png" -resize 192x192 public/app-icon.png
"${IM[@]}" "$TMP/legacy.png" -resize 192x192 public/icon-192.png
"${IM[@]}" "$TMP/legacy.png" -resize 512x512 public/icon-512.png
"${IM[@]}" "$TMP/full.png"   -resize 180x180 public/apple-touch-icon.png
"${IM[@]}" "$TMP/legacy.png" -resize 64x64   public/favicon.png
"${IM[@]}" "$TMP/legacy.png" -resize 192x192 src/assets/didi-partner-logo.png

# 5. Google Play Console listing icon: 512x512, full square (Play rounds it itself).
mkdir -p branding/store
"${IM[@]}" "$TMP/full.png" -resize 512x512 -alpha off branding/store/play-store-icon-512.png

echo "Icons generated from $MASTER"
